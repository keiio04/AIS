<?php
// ============================================================
// backup.php — Secure Database Backup & Export Utility (Area F)
// Restricted exclusively to Administrator role
// ============================================================

require_once __DIR__ . '/../config.php';
require_once __DIR__ . '/../db.php';
require_once __DIR__ . '/../includes/admin_auth.php';

$db = get_db();
$adminId = $_SESSION['user_id'] ?? 0;

$type = $_GET['type'] ?? 'sql'; // 'sql' or 'csv'

if ($type === 'csv') {
    // Export activity_logs to CSV for audit compliance
    log_activity($db, $adminId, 'Export Logs', 'Audit', 'Exported activity logs to CSV');

    $filename = "tala_ais_audit_logs_" . date('Y-m-d_His') . ".csv";
    header('Content-Type: text/csv; charset=utf-8');
    header('Content-Disposition: attachment; filename="' . $filename . '"');
    header('Pragma: no-cache');
    header('Expires: 0');

    $output = fopen('php://output', 'w');
    // UTF-8 BOM for Excel compatibility
    fprintf($output, chr(0xEF).chr(0xBB).chr(0xBF));

    fputcsv($output, ['Log ID', 'Timestamp', 'User ID', 'User Name', 'Role', 'Module', 'Action', 'Description', 'Company ID']);

    $q = "
        SELECT l.id, l.created_at, l.user_id, COALESCE(u.name, 'Unauthenticated') as user_name,
               COALESCE(u.role, 'System') as user_role, l.module, l.action, l.description, l.company_id
        FROM activity_logs l
        LEFT JOIN users u ON l.user_id = u.id
        ORDER BY l.created_at DESC
    ";
    $res = $db->query($q);
    while ($row = $res->fetch_assoc()) {
        fputcsv($output, [
            $row['id'],
            $row['created_at'],
            $row['user_id'] ?? 'N/A',
            $row['user_name'],
            $row['user_role'],
            $row['module'] ?? 'System',
            $row['action'],
            $row['description'] ?? '',
            $row['company_id'] ?? 'N/A'
        ]);
    }
    fclose($output);
    exit;
}

// SQL Backup Export
log_activity($db, $adminId, 'Backup Export', 'Backup', 'Generated and downloaded full database SQL backup');

$filename = "tala_ais_backup_" . date('Y-m-d_His') . ".sql";
header('Content-Type: application/sql');
header('Content-Disposition: attachment; filename="' . $filename . '"');
header('Pragma: no-cache');
header('Expires: 0');

$tables = [];
$res = $db->query("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'");
while ($row = $res->fetch_row()) {
    $tables[] = $row[0];
}

echo "-- ============================================================\n";
echo "-- TALA Accounting Information System (TALA-AIS)\n";
echo "-- Database Backup Export (Area F - Cybersecurity Plan)\n";
echo "-- Generated At: " . date('Y-m-d H:i:s T') . "\n";
echo "-- Generated By: " . htmlspecialchars($_SESSION['user_name'] ?? 'Admin') . " (ID: " . (int)$adminId . ")\n";
echo "-- ============================================================\n\n";
echo "SET FOREIGN_KEY_CHECKS=0;\n";
echo "SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\n";
echo "SET time_zone = '+00:00';\n\n";

foreach ($tables as $table) {
    // Drop & Create Table Structure
    echo "-- ------------------------------------------------------------\n";
    echo "-- Table structure for `$table`\n";
    echo "-- ------------------------------------------------------------\n";
    echo "DROP TABLE IF EXISTS `$table`;\n";
    
    $createRes = $db->query("SHOW CREATE TABLE `$table`");
    $createRow = $createRes->fetch_row();
    echo $createRow[1] . ";\n\n";

    // Table Data
    $dataRes = $db->query("SELECT * FROM `$table`");
    $numRows = $dataRes->num_rows;
    if ($numRows > 0) {
        echo "-- Dumping data for `$table` (" . $numRows . " rows)\n";
        echo "INSERT INTO `$table` VALUES \n";
        $i = 0;
        while ($row = $dataRes->fetch_row()) {
            echo "(";
            $fields = [];
            foreach ($row as $val) {
                if ($val === null) {
                    $fields[] = "NULL";
                } else {
                    $fields[] = "'" . $db->real_escape_string($val) . "'";
                }
            }
            echo implode(", ", $fields) . ")";
            $i++;
            if ($i < $numRows) {
                echo ",\n";
            } else {
                echo ";\n\n";
            }
        }
    }
}

echo "SET FOREIGN_KEY_CHECKS=1;\n";
echo "-- Dump completed at: " . date('Y-m-d H:i:s T') . "\n";
exit;
